export type CollectionKey = keyof typeof COLLECTIONS;
/** Collections plus the single-object resources the client caches. */
export type CacheKey = CollectionKey | "org";

export interface EndpointDef {
  method: HttpMethod;
  path: string;
  module: string;
  summary: string;
  /** snake_case query parameters → meaning. */
  query?: Record<string, string>;
  /** Request body shape (TypeScript name in src/models or src/store). */
  body?: string;
  /** `data` shape on success. */
  returns: string;
  /** RBAC permission the API should check. */
  permission: string;
  /** Cached collections the client reloads after a successful call. */
  invalidates?: CacheKey[];
}

const LIST_QUERY = {
  page: "1-based page (default 1)",
  size: "Page size (default 20, max 500)",
  sort_by: "Field to sort by",
  sort_order: "asc | desc",
  search: "Free-text search",
};

const perm = (resource: string, action: string) => `permission-accounting-${resource}-${action}`;

const list = (
  module: string,
  path: string,
  resource: string,
  returns: string,
  filters: Record<string, string> = {},
): EndpointDef => ({
  method: "GET",
  path,
  module,
  summary: `List ${path.split("/")[1].replace(/-/g, " ")} (paginated)`,
  query: { ...LIST_QUERY, ...filters },
  returns: `{ items: ${returns}[] }`,
  permission: perm(resource, "list"),
});

const get = (module: string, path: string, resource: string, idParam: string, returns: string): EndpointDef => ({
  method: "GET",
  path,
  module,
  summary: `Get one ${resource.replace(/-/g, " ")}`,
  query: { [idParam]: `${resource.replace(/-/g, " ")} id` },
  returns,
  permission: perm(resource, "get"),
});

