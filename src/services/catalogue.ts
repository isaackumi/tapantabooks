import type { HttpMethod } from "@/core/apiClient";

/**
 * Every endpoint the accounting frontend calls: the contract tvs-accounting-bk
 * has to implement. The mock backend serves exactly this list, Settings → API
 * renders it, and docs/API_ENDPOINTS.md is generated from it.
 */

/**
 * Reference data the client caches, each loaded in full from one list endpoint at sign-in.
 * Transactions (journals, documents, payments, statement lines, imports, audit events) are
 * never cached: screens read them page by page or through report endpoints.
 */
export const COLLECTIONS = {
  accounts: "/accounts/list",
  taxCodes: "/tax-codes/list",
  customers: "/customers/list",
  suppliers: "/suppliers/list",
  bankAccounts: "/bank-accounts/list",
  periods: "/fiscal-periods/list",
  dimensions: "/dimensions/list",
  dataSources: "/data-sources/list",
  fieldMappings: "/field-mappings/list",
  customFields: "/custom-fields/list",
  currencies: "/currencies/list",
  exchangeRates: "/exchange-rates/list",
  rules: "/accounting-rules/list",
} as const;

export type CollectionKey = keyof typeof COLLECTIONS;
/** Collections plus the single-object resources the client caches. */
export type CacheKey = CollectionKey | "org";

export interface EndpointDef {
  method: HttpMethod;
  path: string;
  module: string;
  summary: string;
  /** snake_case query parameters → meaning. */
  query?: Record<string, string>;
  /** Request body shape (TypeScript name in src/models or src/store). */
  body?: string;
  /** `data` shape on success. */
  returns: string;
  /** RBAC permission the API should check. */
  permission: string;
  /** Cached collections the client reloads after a successful call. */
  invalidates?: CacheKey[];
}

const LIST_QUERY = {
  page: "1-based page (default 1)",
  size: "Page size (default 20, max 100)",
  sort_by: "Field to sort by; cf_<key> sorts by a custom field",
  sort_order: "asc | desc",
  search: "Free-text search",
};

/** For entities that carry custom fields. */
const CUSTOM_FIELD_QUERY = {
  "cf_<key>": "Custom field equals value; for yes/no fields `false` also matches records where it was never set",
};

const perm = (resource: string, action: string) => `permission-accounting-${resource}-${action}`;

const list = (
  module: string,
  path: string,
  resource: string,
  returns: string,
  filters: Record<string, string> = {},
): EndpointDef => ({
  method: "GET",
  path,
  module,
  summary: `List ${path.split("/")[1].replace(/-/g, " ")} (paginated)`,
  query: { ...LIST_QUERY, ...filters },
  returns: `{ items: ${returns}[] }`,
  permission: perm(resource, "list"),
});

const paymentList = (module: string, path: string, resource: string, filters: Record<string, string>): EndpointDef => ({
  ...list(module, path, resource, "PaymentListItem", {
    ...filters,
    method: "BANK_TRANSFER | MOBILE_MONEY | CASH | CHEQUE",
    bank_account_id: "Bank account id",
    state: "POSTED | VOID",
    from_date: "YYYY-MM-DD",
    to_date: "YYYY-MM-DD",
  }),
  returns: "PaymentListData: { items: PaymentListItem[], totals: { count, base_amount } } (totals cover every matching row that is not void)",
});

/** Figures behind a list page's cards and tab counts; unaffected by list filters. */
const statistics = (module: string, path: string, resource: string, returns: string, summary: string): EndpointDef => ({
  method: "GET",
  path,
  module,
  summary,
  returns,
  permission: perm(resource, "list"),
});

const get = (module: string, path: string, resource: string, idParam: string, returns: string): EndpointDef => ({
  method: "GET",
  path,
  module,
  summary: `Get one ${resource.replace(/-/g, " ")}`,
  query: { [idParam]: `${resource.replace(/-/g, " ")} id` },
  returns,
  permission: perm(resource, "get"),
});

